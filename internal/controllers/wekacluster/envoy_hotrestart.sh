#!/bin/bash
# Hot-restart the running envoy with the immediate drain policy (forwarder NDU
# stages E / F0). Runs INSIDE the envoy container as `bash -c <script>`, started
# by the agent's exec_in_container on the s3 container hook's request (management
# verb s3_fwd_envoy_hotrestart). Idempotent: exits 0 at once when the policy is
# already immediate or the hot restart was already registered. Logs to
# /data/log/ndu-envoy-hotrestart.log inside the container (host: the envoy
# container's logs directory).
#
# The image's start_envoy.sh fixes the command line, and the drain flags have no
# config-file form, so a child process is started by Envoy's hot restart
# (epoch + 1, same base-id and socket path) carrying --drain-time-s 2
# --drain-strategy immediate. It takes the listening sockets over with no gap;
# the parent stops accepting at once and is terminated after PARENT_SHUTDOWN_S.
# A second s6 longrun (envoy2) supervises the child; the stock service's
# `finish` script, which halts the container on any envoy exit, is replaced by
# a no-op and the stock service set once-at-most. Everything lives on /run
# (tmpfs): a container restart returns the host to stock.
set -euo pipefail
mkdir -p /data/log
exec >> /data/log/ndu-envoy-hotrestart.log 2>&1
echo "=== $(date -u +%FT%TZ) hot-restart script start"

DRAIN_TIME_S=2
PARENT_SHUTDOWN_S=30
ADMIN=127.0.0.1:9901
SVC=/run/service/envoy2
STDERR_LOG=/data/log/envoy2.stderr

info=$(curl -sf --max-time 2 "http://$ADMIN/server_info") || {
    echo "no live envoy answering on $ADMIN; nothing to hot-restart" >&2
    exit 1
}
strategy=$(sed -n 's/.*"drain_strategy": *"\([A-Za-z]*\)".*/\1/p' <<<"$info" | head -1)
drain_time=$(sed -n 's/.*"drain_time": *"\([0-9]*\)s".*/\1/p' <<<"$info" | head -1)
if [[ ${strategy,,} == immediate && -n $drain_time && $drain_time -le 5 ]]; then
    echo "envoy already on the immediate drain policy (${drain_time}s); nothing to do"
    exit 0
fi
if [[ -d $SVC ]]; then
    echo "$SVC already registered; a hot restart is in progress or was issued before"
    exit 0
fi
base_id=$(sed -n 's/.*"base_id": *"\([0-9]*\)".*/\1/p' <<<"$info" | head -1)
epoch=$(sed -n 's/.*"restart_epoch": *\([0-9]*\).*/\1/p' <<<"$info" | head -1)
if [[ -z $base_id ]]; then
    echo "cannot read base_id from /server_info" >&2
    exit 1
fi
echo "live envoy: epoch=${epoch:-?} base_id=$base_id strategy=${strategy:-?} drain_time=${drain_time:-?}s; envoy2 starts at epoch $((epoch + 1))"

# Quoted heredoc: nothing is expanded here; placeholders are filled by sed below.
# The exec stays on one line on purpose: backslash continuations inside a
# generated script are easy to corrupt.
run_template=$(cat <<'EOF'
#!/bin/bash
# s6 longrun for envoy2 (generated by the S3 NDU hook's envoy_hotrestart.sh).
# Epoch: live envoy's + 1 for a hot restart, 0 when no envoy answers the admin port.
epoch=0
if info=$(curl -sf --max-time 2 http://@ADMIN@/server_info); then
    live=$(sed -n 's/.*"restart_epoch": *\([0-9]*\).*/\1/p' <<<"$info" | head -1)
    [[ -n $live ]] && epoch=$((live + 1))
fi
echo "envoy2: starting envoy epoch $epoch (drain @DRAIN@s immediate, parent-shutdown @PSHUT@s)"
echo -900 > /proc/self/oom_score_adj
exec envoy -c /opt/weka/envoy/envoy_static_conf.yaml --log-path /data/log/envoy.log -l info --component-log-level upstream:debug,admin:info,assert:debug,backtrace:debug,config:debug,filter:debug,hc:info,main:info,matcher:debug --socket-path /opt/weka/envoy/envoy_sock --base-id @BASE_ID@ --restart-epoch $epoch --skip-hot-restart-on-no-parent --parent-shutdown-time-s @PSHUT@ --drain-time-s @DRAIN@ --drain-strategy immediate 2>>@STDERR_LOG@
EOF
)
run_script=$(sed -e "s|@ADMIN@|$ADMIN|g" -e "s|@BASE_ID@|$base_id|g" \
                 -e "s|@DRAIN@|$DRAIN_TIME_S|g" -e "s|@PSHUT@|$PARENT_SHUTDOWN_S|g" \
                 -e "s|@STDERR_LOG@|$STDERR_LOG|g" <<<"$run_template")

mkdir -p "$SVC"
printf '%s\n' "$run_script" > "$SVC/run"
chmod +x "$SVC/run"
bash -n "$SVC/run"
cat > "$SVC/finish" <<'EOF'
#!/bin/bash
# s6 runs this after ./run exits; s6 then restarts ./run after about 1 s.
echo "envoy2: envoy exited (code=$1 signal=$2); s6 will restart it"
EOF
chmod +x "$SVC/finish"

# The stock finish script halts the whole container when the envoy process
# exits; with the child terminating the parent after PARENT_SHUTDOWN_S that
# would halt the container and take envoy2 down with it.
if [[ ! -f /run/service/envoy/finish.orig ]]; then
    cp /run/service/envoy/finish /run/service/envoy/finish.orig
fi
cat > /run/service/envoy/finish <<'EOF'
#!/bin/bash
# Neutralized by the S3 NDU hook (original kept as finish.orig): the stock
# script halts the container when envoy exits.
echo "envoy (epoch-0 service): exited code=$1 signal=$2; container kept up for envoy2"
exit 0
EOF
chmod +x /run/service/envoy/finish

# Leave the parent running, never restart it once it exits; then register
# envoy2, which s6-svscan supervises and starts at once.
s6-svc -O /run/service/envoy
s6-svscanctl -a /run/service
echo "envoy2 registered; the child takes the listeners over and the parent exits in ${PARENT_SHUTDOWN_S}s"
